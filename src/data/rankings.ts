export function getRankingBySlug(slug: string): Ranking | undefined {
  return rankings.find((r) => r.slug === slug);
}

export function getFeaturedRankings(): Ranking[] {
  return rankings.filter((r) => r.isFeatured);
}

export function getTrendingRankings(): Ranking[] {
  return rankings.filter((r) => r.isTrending);
}

export function getRankingsByCategory(category: string): Ranking[] {
  return rankings.filter(
    (r) => r.category.toLowerCase() === category.toLowerCase()
  );
}
